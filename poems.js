const poemasContainer = document.querySelector(".poemas");
const next = document.querySelector(".next");
const prev = document.querySelector(".prev");

let current = 0;

function renderpoemas(index) {

    const poemas = poemasas[index];

    poemasContainer.innerHTML = `
        <span class="year">${poemas.year}</span>

        ${poemas.title ? `<h2>${poemas.title}</h2>` : ""}

        <p>${poemas.text.replace(/\n/g, "<br>")}</p>

        <div class="counter">
            ${index + 1} / ${poemasas.length}
        </div>
    `;
}

renderpoemas(current);

next.addEventListener("click", () => {
    current = (current + 1) % poemasas.length;
    renderpoemas(current);
});

prev.addEventListener("click", () => {
    current = (current - 1 + poemasas.length) % poemasas.length;
    renderpoemas(current);
});

// Navegación con teclado
document.addEventListener("keydown", (e) => {

    if (e.key === "ArrowRight") {
        next.click();
    }

    if (e.key === "ArrowLeft") {
        prev.click();
    }

});